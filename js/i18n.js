window.T = function (key) {
  var lang = window.Store ? window.Store.get('lang') : 'ro';
  var pack = window.STRINGS[lang] || window.STRINGS.ro;
  var val = pack[key];
  return val === undefined ? key : val;
};

// Random pick from a string list (praise messages).
window.TR = function (key) {
  var list = window.T(key);
  if (!list || !list.length) return '';
  return list[Math.floor(Math.random() * list.length)];
};

// Country name in the active language.
window.NAME = function (country) {
  return window.Store.get('lang') === 'en' ? country.en : country.ro;
};
